import mongoose from 'mongoose';

/**
 * Embedded line item schema.
 *
 * Note (Embedding vs Referencing): `name`, `sku`, and `unitPrice` are stored
 * as a snapshot at order creation time so later product price or name changes
 * never alter historical sales orders.
 */
const salesOrderItemSchema = new mongoose.Schema(
  {
    product: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Product',
      required: true,
    },
    name: {
      type: String,
      required: true,
      trim: true,
    },
    sku: {
      type: String,
      required: true,
      trim: true,
    },
    quantity: {
      type: Number,
      required: true,
      min: 1,
    },
    unitPrice: {
      type: Number,
      required: true,
      min: 0,
    },
  },
  { _id: false }
);

const salesOrderSchema = new mongoose.Schema(
  {
    orderNumber: {
      type: String,
      required: true,
      unique: true,
      trim: true,
    },
    customerName: {
      type: String,
      required: true,
      trim: true,
    },
    customerPhone: {
      type: String,
      trim: true,
      default: '',
    },
    status: {
      type: String,
      enum: ['pending', 'confirmed', 'completed', 'cancelled'],
      default: 'pending',
    },
    items: {
      type: [salesOrderItemSchema],
      validate: [(v) => v.length > 0, 'Sales order must have at least one item'],
    },
    total: {
      type: Number,
      required: true,
      min: 0,
    },
    createdBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
    },
  },
  { timestamps: true }
);

salesOrderSchema.index({ createdAt: -1 });

export const SalesOrder = mongoose.model('SalesOrder', salesOrderSchema);
